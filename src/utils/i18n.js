const LANG_STORAGE_KEY = 'avalive_current_language';

export function getCurrentLanguage() {
  if (typeof window === 'undefined') return 'vi';
  try {
    const saved = localStorage.getItem(LANG_STORAGE_KEY);
    if (saved && TRANSLATIONS[saved]) return saved;
  } catch {}
  return 'vi';
}

export function setCurrentLanguage(langCode) {
  if (typeof window === 'undefined') return;
  try {
    const valid = TRANSLATIONS[langCode] ? langCode : 'vi';
    localStorage.setItem(LANG_STORAGE_KEY, valid);
    window.dispatchEvent(new CustomEvent('avalive_language_changed', { detail: { language: valid } }));
    return valid;
  } catch {}
  return 'vi';
}

export function t(key, lang = null) {
  const currentLang = lang || getCurrentLanguage();
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.vi;
  return dict[key] || TRANSLATIONS.vi[key] || key;
}
